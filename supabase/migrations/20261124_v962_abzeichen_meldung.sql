-- v962 · Charles 24.11.2026: „Die Kinder sollten es in der Kinder-App als erledigt markieren … und dann muss es eine Nachricht
-- ganz oben in der Eltern-App geben: ‚Dein Kind hat eine … Übung in der Adler-Akademie absolviert. Bitte gib es frei.‘“
-- Eine Zeile = ein offenes „Ich hab's geschafft!“ eines Kindes für ein Technik-Abzeichen. Bestätigen die Eltern, vergibt die App
-- die Federn wie bisher (xp_award_event, Quelle abzeichen/abzeichen_silber) und löscht die Zeile; „Noch nicht“ löscht sie nur.
-- Die Tabelle hält also nur Offenes – keine Bewertung, kein Verlauf. Kindergerät nur mit Appzeit übrig, wie bei kind_training.
create table if not exists public.abzeichen_meldung (
  id bigint generated by default as identity primary key,
  spieler_id bigint not null references public.kader(id) on delete cascade,
  abzeichen text not null check (abzeichen ~ '^ab2?_[a-z]+$'),
  quelle text not null check (quelle in ('abzeichen', 'abzeichen_silber')),
  created_at timestamptz not null default now(),
  unique (spieler_id, abzeichen),
  check ((abzeichen like 'ab2\_%') = (quelle = 'abzeichen_silber'))
);
comment on table public.abzeichen_meldung is 'v962: offene „Ich hab''s geschafft!“-Meldungen der Kinder für Technik-Abzeichen; Eltern bestätigen (Federn) oder verwerfen, danach wird die Zeile gelöscht.';
alter table public.abzeichen_meldung enable row level security;

drop policy if exists am_lesen on public.abzeichen_meldung;
create policy am_lesen on public.abzeichen_meldung for select to authenticated
  using (public.is_trainer() or public.is_parent_of(spieler_id) or public.is_kind_selbst(spieler_id));
drop policy if exists am_melden on public.abzeichen_meldung;
create policy am_melden on public.abzeichen_meldung for insert to authenticated
  with check (public.is_parent_of(spieler_id) or (public.is_kind_selbst(spieler_id) and public.kind_zeit_uebrig()));
drop policy if exists am_erledigen on public.abzeichen_meldung;
create policy am_erledigen on public.abzeichen_meldung for delete to authenticated
  using (public.is_trainer() or public.is_parent_of(spieler_id));

revoke all on public.abzeichen_meldung from anon;
grant select, insert, delete on public.abzeichen_meldung to authenticated;

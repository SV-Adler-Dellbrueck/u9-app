-- Sichtbar ist eine Datei, wenn sie zu einer veröffentlichten Ausgabe gehört (Trainer: immer).
-- security definer, damit die Prüfung nicht an der RLS von heft_ausgabe hängt (vgl. v731).
create or replace function public.heft_pfad_sichtbar(p_name text) returns boolean
language sql stable security definer set search_path to 'public' as $$
  select public.is_trainer() or (public.sitzung_gueltig() and exists (
    select 1 from public.heft_ausgabe a
    where a.status = 'veroeffentlicht'
      and (a.titelbild_pfad = p_name or a.audio_pfad = p_name
           or exists (select 1 from jsonb_array_elements(a.portraet_privatfotos) e where e->>'pfad' = p_name))));
$$;
revoke all on function public.heft_pfad_sichtbar(text) from public, anon;
grant execute on function public.heft_pfad_sichtbar(text) to authenticated;


-- 1) Ausgaben
create table if not exists public.heft_ausgabe (
  id bigint generated by default as identity primary key,
  team text not null default 'adler1',
  nummer int not null check (nummer > 0),
  termin_id bigint references public.termine(id) on delete set null,
  schlagzeile text check (schlagzeile is null or char_length(schlagzeile) <= 40),
  teaser_spieltag text check (teaser_spieltag is null or char_length(teaser_spieltag) <= 45),
  teaser_portraet text check (teaser_portraet is null or char_length(teaser_portraet) <= 45),
  teaser_tag text check (teaser_tag is null or char_length(teaser_tag) <= 45),
  titelbild_pfad text,
  audio_pfad text,
  audio_sekunden int check (audio_sekunden is null or audio_sekunden >= 0),
  anpfiff text,
  spieltag_text text,
  zitat text,
  eltern_dank text,
  sonderzeile text,
  foto_ids bigint[] not null default '{}' check (cardinality(foto_ids) <= 6),
  portraet_spieler_id bigint references public.kader(id) on delete set null,
  portraet_spitzname boolean not null default false,   -- Spitzname nur, wenn Charles ihn ausdrücklich will
  portraet_einleitung text,
  portraet_trainersatz text,
  portraet_privatfotos jsonb not null default '[]'::jsonb
    check (jsonb_typeof(portraet_privatfotos) = 'array' and jsonb_array_length(portraet_privatfotos) <= 2),
  training_leitfrage text,
  training_text text,
  tag_lernen text,
  tag_lustig text,
  tag_quellen text,
  kommentar text,
  status text not null default 'entwurf' check (status in ('entwurf','veroeffentlicht')),
  veroeffentlicht_am timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (team, nummer)
);
comment on table public.heft_ausgabe is 'v733: Adler Nest – eine Ausgabe je Spieltag; Eltern und Kinder lesen nur Veröffentlichtes über heft_ausgabe_lesen/heft_medien';
comment on column public.heft_ausgabe.tag_quellen is 'Quellen zu „An diesem Tag“ – nur für das Trainerteam, wird nie an Eltern ausgeliefert';
comment on column public.heft_ausgabe.portraet_privatfotos is 'bis 2 Einträge {pfad, unterschrift, einverstanden:true} im Bucket heft_media';

-- Privatfotos: jedes braucht Pfad, Unterschrift und das Einverständnis der Familie.
create or replace function public.heft_ausgabe_vor() returns trigger
language plpgsql set search_path to 'public' as $$
declare e jsonb;
begin
  for e in select * from jsonb_array_elements(coalesce(new.portraet_privatfotos,'[]'::jsonb)) loop
    if jsonb_typeof(e) <> 'object' or coalesce(e->>'pfad','') = '' then raise exception 'Privatfoto ohne Datei'; end if;
    if coalesce((e->>'einverstanden')::boolean, false) is not true then raise exception 'Privatfoto ohne Einverständnis der Familie'; end if;
  end loop;
  if new.status = 'veroeffentlicht' and new.veroeffentlicht_am is null then new.veroeffentlicht_am := now(); end if;
  if new.status = 'entwurf' then new.veroeffentlicht_am := null; end if;
  new.updated_at := now();
  return new;
end $$;
drop trigger if exists heft_ausgabe_vor on public.heft_ausgabe;
create trigger heft_ausgabe_vor before insert or update on public.heft_ausgabe
  for each row execute function public.heft_ausgabe_vor();

alter table public.heft_ausgabe enable row level security;

--    rufe_push_faellig kürzt ohnehin auf 110 Zeichen, die Suche (ilike) kennt keine feste Länge.
-- 2. Privater Bucket rufe-anhang: 10 MB, Bilder, PDF, Word, Excel, PowerPoint – keine Makroformate, kein SVG/HTML.
-- 3. Tabelle rufe_anhang mit RLS: lesen wie rn_lesen, schreiben nur der Autor (höchstens vier je Ruf), ändern nie,
--    löschen nur Trainer.
-- 4. rufe_senden: Ruf und Anhänge in EINEM Aufruf (security invoker – der Trigger rufe_vor_insert setzt den Autor
--    weiter aus auth.uid(), die RLS gilt wie beim direkten Schreiben). Scheitert ein Anhang, gibt es keinen Ruf.
-- 5. rufe_anhaenge_loeschen: Trainer entfernt Zeilen (die Dateien löscht die App über die Storage-API) und
--    markiert den Ruf mit anhang_entfernt_am („Anhang entfernt“).

-- ── 1. Zeichenlimit ─────────────────────────────────────────────────────────────
alter table public.rufe_nachricht drop constraint if exists rufe_nachricht_text_check;
alter table public.rufe_nachricht add constraint rufe_nachricht_text_check
  check (length(trim(both from text)) >= 1 and length(trim(both from text)) <= 5000);
alter table public.rufe_nachricht add column if not exists anhang_entfernt_am timestamptz;

create or replace function public.rufe_bearbeiten(p_id bigint, p_text text)
 returns boolean language plpgsql security definer set search_path to 'public' as $function$
begin
  if not public.darf_rufen() then raise exception 'not authorized'; end if;
  if length(trim(coalesce(p_text,''))) not between 1 and 5000 then raise exception 'text'; end if;
  update rufe_nachricht set text=p_text, bearbeitet_am=now()
   where id=p_id and autor=auth.uid() and archiviert_am is null;
  if not found then raise exception 'not authorized'; end if;
  return true;
end $function$;


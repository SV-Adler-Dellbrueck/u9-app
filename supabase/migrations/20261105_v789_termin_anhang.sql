-- v789 · Anhänge am Termin (Charles 05.11.: „Spielplan der Gastgeber im Termin für die Eltern anhängen“)
-- Gebaut nach dem Muster von v736 (rufe_anhang). NICHT von Claude Code ausgeführt: Charles spielt sie im SQL-Editor ein, bevor der PR gemergt wird.
-- Lokal gegen ein Postgres 16 mit tests/sql/supabase-attrappe.sql geprüft (tests/sql/v789-termin-anhang.sql).
--
-- 1. Privater Bucket termin-anhang: 10 MB, nur Bilder (JPEG, PNG, WebP, HEIC) und PDF – kein Office, kein SVG/HTML.
-- 2. Tabelle termin_anhang: höchstens drei je Termin; lesen darf, wer den Termin sehen darf (die Regel von termine_read gilt
--    über die Unterabfrage mit); anlegen und löschen nur Trainer; ändern nie.
-- 3. Speicher-Regeln: hochladen und löschen nur Trainer, lesen wie die Tabelle.

-- ── 1. Bucket ──────────────────────────────────────────────────────────────────
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('termin-anhang', 'termin-anhang', false, 10485760,
        array['image/jpeg','image/png','image/webp','image/heic','application/pdf'])
on conflict (id) do update set public = false, file_size_limit = excluded.file_size_limit, allowed_mime_types = excluded.allowed_mime_types;

-- Pfad: <termin_id>/<uuid>.<endung> – genau diese Form, sonst nichts
create or replace function public.termin_anhang_pfad_ok(p_pfad text) returns boolean
language sql immutable set search_path to 'public' as $$
  select coalesce(p_pfad ~ '^[0-9]{1,18}/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.(jpg|jpeg|png|webp|heic|pdf)$', false);
$$;
create or replace function public.termin_anhang_termin(p_pfad text) returns bigint
language sql immutable set search_path to 'public' as $$
  select case when public.termin_anhang_pfad_ok(p_pfad) then split_part(p_pfad, '/', 1)::bigint end;
$$;

-- ── 2. Tabelle ─────────────────────────────────────────────────────────────────
create table if not exists public.termin_anhang (
  id bigint generated by default as identity primary key,
  termin_id bigint not null references public.termine(id) on delete cascade,
  pfad text not null unique check (public.termin_anhang_pfad_ok(pfad)),
  titel text not null check (length(btrim(titel)) between 1 and 80),
  name text not null check (length(name) between 1 and 120),
  mime text not null check (mime in ('image/jpeg','image/png','image/webp','image/heic','application/pdf')),
  groesse bigint not null check (groesse between 1 and 10485760),
  created_at timestamptz not null default now(),
  check (public.termin_anhang_termin(pfad) = termin_id)
);
comment on table public.termin_anhang is 'v789: Anhänge zu Terminen (Dateien im Bucket termin-anhang), z. B. der Spielplan der Gastgeber. Lesen wer den Termin sieht, schreiben und löschen nur Trainer.';
create index if not exists termin_anhang_termin on public.termin_anhang(termin_id);
alter table public.termin_anhang enable row level security;

-- höchstens drei je Termin; die Datei muss schon hochgeladen sein
create or replace function public.termin_anhang_vor_insert() returns trigger
language plpgsql security definer set search_path to 'public' as $$
begin
  if (select count(*) from termin_anhang a where a.termin_id = new.termin_id) >= 3 then raise exception 'hoechstens drei anhaenge'; end if;
  if not exists (select 1 from storage.objects o where o.bucket_id = 'termin-anhang' and o.name = new.pfad) then raise exception 'anhang datei'; end if;
  new.created_at := now();
  return new;
end $$;
drop trigger if exists termin_anhang_vor on public.termin_anhang;
create trigger termin_anhang_vor before insert on public.termin_anhang for each row execute function public.termin_anhang_vor_insert();

drop policy if exists ta_lesen on public.termin_anhang;
create policy ta_lesen on public.termin_anhang for select to authenticated using (
  exists (select 1 from public.termine t where t.id = termin_id));     -- termine_read gilt mit: Trainermeetings bleiben beim Trainerteam
drop policy if exists ta_schreiben on public.termin_anhang;
create policy ta_schreiben on public.termin_anhang for insert to authenticated with check (public.is_trainer());
drop policy if exists ta_loeschen on public.termin_anhang;
create policy ta_loeschen on public.termin_anhang for delete to authenticated using (public.is_trainer());
-- kein UPDATE: Anhänge werden nie geändert (neu hochladen, alten löschen)
revoke all on public.termin_anhang from anon;
grant select, insert, delete on public.termin_anhang to authenticated;

-- Darf der Anfragende die Datei lesen? Dieselbe Regel wie die Tabelle.
create or replace function public.termin_anhang_lesbar(p_pfad text) returns boolean
language sql stable security definer set search_path to 'public' as $$
  select exists (select 1 from termin_anhang a join termine t on t.id = a.termin_id
                 where a.pfad = p_pfad and (t.typ <> 'trainermeeting' or public.is_trainer()));
$$;
revoke all on function public.termin_anhang_lesbar(text) from public, anon;
grant execute on function public.termin_anhang_lesbar(text) to authenticated;
grant execute on function public.termin_anhang_pfad_ok(text) to authenticated;
grant execute on function public.termin_anhang_termin(text) to authenticated;

-- ── 3. Speicher-Regeln ───────────────────────────────────────────────────────────────
drop policy if exists "termin-anhang hochladen" on storage.objects;
create policy "termin-anhang hochladen" on storage.objects for insert to authenticated with check (
  bucket_id = 'termin-anhang' and public.is_trainer() and public.termin_anhang_pfad_ok(name)
  and exists (select 1 from public.termine t where t.id = public.termin_anhang_termin(name)));
drop policy if exists "termin-anhang lesen" on storage.objects;
create policy "termin-anhang lesen" on storage.objects for select to authenticated using (
  bucket_id = 'termin-anhang' and (public.is_trainer() or public.termin_anhang_lesbar(name)));
drop policy if exists "termin-anhang loeschen" on storage.objects;
create policy "termin-anhang loeschen" on storage.objects for delete to authenticated using (
  bucket_id = 'termin-anhang' and public.is_trainer());
-- kein UPDATE im Bucket (Dateien werden nie überschrieben)

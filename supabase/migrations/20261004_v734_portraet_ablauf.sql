-- 4) Kind festlegen: legt die Einreichung an und rechnet die Fristen (Mittwoch und Freitag vor dem Spieltag, 20 Uhr)
create or replace function public.portraet_anfragen(p_spieler bigint, p_termin bigint) returns public.portraet_einreichung
language plpgsql security definer set search_path to 'public' as $$
declare d date; mi date; fr date; neu public.portraet_einreichung;
begin
  if not public.is_trainer() then raise exception 'Nur Trainer'; end if;
  select datum::date into d from public.termine where id = p_termin and typ in ('spiel','turnier') and datum ~ '^\d{4}-\d{2}-\d{2}$';
  if d is null then raise exception 'Spieltag nicht gefunden'; end if;
  mi := d - ((extract(isodow from d)::int - 3 + 7) % 7); if mi >= d then mi := mi - 7; end if;
  fr := d - ((extract(isodow from d)::int - 5 + 7) % 7); if fr >= d then fr := fr - 7; end if;
  insert into public.portraet_einreichung(spieler_id, termin_id, frist_eltern, frist_trainer)
  values (p_spieler, p_termin, (mi + time '20:00') at time zone 'Europe/Berlin', (fr + time '20:00') at time zone 'Europe/Berlin')
  returning * into neu;
  return neu;
end $$;
revoke all on function public.portraet_anfragen(bigint, bigint) from public, anon;
grant execute on function public.portraet_anfragen(bigint, bigint) to authenticated;

-- 5) Eltern reichen ein oder ziehen das Einverständnis zurück. Rückgabe: Pfade, die nicht mehr gebraucht werden
--    (die App löscht sie im Speicher). Beim Rückzug verschwinden die Fotos auch aus der Ausgabe.
create or replace function public.portraet_einreichen(p_einreichung bigint, p_einverstanden boolean, p_privatfotos jsonb default '[]'::jsonb)
returns table(pfad text)
language plpgsql security definer set search_path to 'public' as $$
declare e public.portraet_einreichung; neu jsonb := '[]'::jsonb; f jsonb; alt text[];
begin
  select * into e from public.portraet_einreichung where id = p_einreichung;
  if e.id is null or not (public.is_trainer() or (public.is_parent_of(e.spieler_id) and e.status <> 'uebernommen')) then
    raise exception 'Keine Einreichung'; end if;
  alt := array(select x->>'pfad' from jsonb_array_elements(e.privatfotos) x);
  if p_einverstanden then
    if jsonb_typeof(coalesce(p_privatfotos,'[]'::jsonb)) <> 'array' or jsonb_array_length(coalesce(p_privatfotos,'[]'::jsonb)) > 2 then
      raise exception 'Höchstens 2 Privatfotos'; end if;
    for f in select * from jsonb_array_elements(coalesce(p_privatfotos,'[]'::jsonb)) loop
      if coalesce(f->>'pfad','') !~ ('^einreichung/' || e.id || '/[^/]+$') then raise exception 'Fremder Pfad'; end if;
      neu := neu || jsonb_build_object('pfad', f->>'pfad', 'unterschrift', left(coalesce(f->>'unterschrift',''), 80));
    end loop;
    update public.portraet_einreichung set privatfotos = neu, einverstanden_am = now(), einverstanden_von = auth.uid(),
      status = case when status = 'uebernommen' then status else 'eingereicht' end where id = e.id;
  else
    update public.portraet_einreichung set privatfotos = '[]'::jsonb, einverstanden_am = null, einverstanden_von = null,
      status = case when status = 'uebernommen' then status else 'angefragt' end where id = e.id;
    -- aus jeder Ausgabe entfernen, die diese Fotos trägt
    update public.heft_ausgabe a set portraet_privatfotos = coalesce((select jsonb_agg(x) from jsonb_array_elements(a.portraet_privatfotos) x
        where not (x->>'pfad' = any(alt))), '[]'::jsonb)
      where exists (select 1 from jsonb_array_elements(a.portraet_privatfotos) x where x->>'pfad' = any(alt));
  end if;
  return query select u from unnest(alt) u
    where not exists (select 1 from jsonb_array_elements(case when p_einverstanden then neu else '[]'::jsonb end) x where x->>'pfad' = u);
end $$;
revoke all on function public.portraet_einreichen(bigint, boolean, jsonb) from public, anon;
grant execute on function public.portraet_einreichen(bigint, boolean, jsonb) to authenticated;

-- 6) Privatfotos einer Ausgabe nur aus einer Einreichung mit Einverständnis (ersetzt die Prüfung aus v733).
--    Veröffentlichen markiert die Einreichung des Porträtkinds als übernommen.
create or replace function public.heft_ausgabe_vor() returns trigger
language plpgsql set search_path to 'public' as $$
declare f jsonb;
begin
  for f in select * from jsonb_array_elements(coalesce(new.portraet_privatfotos,'[]'::jsonb)) loop
    if jsonb_typeof(f) <> 'object' or coalesce(f->>'pfad','') = '' then raise exception 'Privatfoto ohne Datei'; end if;
    if not exists (select 1 from public.portraet_einreichung e
                    where e.spieler_id = new.portraet_spieler_id and e.einverstanden_am is not null
                      and exists (select 1 from jsonb_array_elements(e.privatfotos) x where x->>'pfad' = f->>'pfad')) then
      raise exception 'Privatfoto ohne Einverständnis der Familie';
    end if;
  end loop;
  if new.status = 'veroeffentlicht' and new.veroeffentlicht_am is null then new.veroeffentlicht_am := now(); end if;
  if new.status = 'entwurf' then new.veroeffentlicht_am := null; end if;
  new.updated_at := now();
  return new;
end $$;
create or replace function public.heft_ausgabe_nach() returns trigger
language plpgsql security definer set search_path to 'public' as $$
begin
  if new.status = 'veroeffentlicht' and new.portraet_spieler_id is not null then
    update public.portraet_einreichung set status = 'uebernommen', ausgabe_id = new.id
     where spieler_id = new.portraet_spieler_id and status <> 'uebernommen';
  end if;
  return null;
end $$;
drop trigger if exists heft_ausgabe_nach on public.heft_ausgabe;
create trigger heft_ausgabe_nach after insert or update of status, portraet_spieler_id on public.heft_ausgabe
  for each row execute function public.heft_ausgabe_nach();

-- 7) Speicher heft_media: Eltern schreiben und lesen nur unter einreichung/<id>/ ihrer eigenen offenen Einreichung
create or replace function public.heft_einreichung_eigen(p_name text) returns boolean
language sql stable security definer set search_path to 'public' as $$
  select p_name ~ '^einreichung/[0-9]+/[^/]+$' and exists (
    select 1 from public.portraet_einreichung e
     where e.id = split_part(p_name, '/', 2)::bigint and e.status <> 'uebernommen' and public.is_parent_of(e.spieler_id));
$$;
revoke all on function public.heft_einreichung_eigen(text) from public, anon;
grant execute on function public.heft_einreichung_eigen(text) to authenticated;
create or replace function public.heft_pfad_sichtbar(p_name text) returns boolean
language sql stable security definer set search_path to 'public' as $$
  select public.is_trainer() or public.heft_einreichung_eigen(p_name) or (public.sitzung_gueltig() and exists (
    select 1 from public.heft_ausgabe a
    where a.status = 'veroeffentlicht'
      and (a.titelbild_pfad = p_name or a.audio_pfad = p_name
           or exists (select 1 from jsonb_array_elements(a.portraet_privatfotos) e where e->>'pfad' = p_name))));
$$;
drop policy if exists "heft_media eltern schreiben" on storage.objects;
create policy "heft_media eltern schreiben" on storage.objects for insert to authenticated
  with check (bucket_id = 'heft_media' and public.heft_einreichung_eigen(name));
drop policy if exists "heft_media eltern loeschen" on storage.objects;
create policy "heft_media eltern loeschen" on storage.objects for delete to authenticated
  using (bucket_id = 'heft_media' and public.heft_einreichung_eigen(name));

-- 8) Trainingsbeteiligung: nur der Satz, und nur ab der Schwelle; gerechnet aus der Anwesenheitsliste der Saison.
--    Trainings ohne Liste zählen nicht; unter 6 erfassten Trainings kein Satz. Juli-Listen führen Vornamen statt IDs.
create or replace function public.portraet_beteiligung(p_spieler bigint) returns text
language plpgsql stable security definer set search_path to 'public' as $$
declare k public.kader; v_ab date; v_heute date := (now() at time zone 'Europe/Berlin')::date;
        n_erfasst int; n_dabei int; v_schwelle int;
begin
  if not public.is_trainer() then return null; end if;
  select * into k from public.kader where id = p_spieler; if k.id is null then return null; end if;
  v_ab := make_date(case when extract(month from v_heute) >= 7 then extract(year from v_heute)::int else extract(year from v_heute)::int - 1 end, 7, 1);
  select coalesce(max(portraet_schwelle), 90) into v_schwelle from public.team_config;
  with t as (
    select distinct te.datum from public.termine te
     where te.typ = 'training' and coalesce(te.platz_status,'') <> 'abgesagt'
       and te.datum ~ '^\d{4}-\d{2}-\d{2}$' and te.datum::date between v_ab and v_heute
  ), e as (
    select coalesce(a.data -> (k.id::text), a.data -> k.name) eintrag
      from t join public.anwesenheit a on a.datum = t.datum
  )
  select count(*) filter (where eintrag is not null), count(*) filter (where (eintrag->>'da')::boolean)
    into n_erfasst, n_dabei from e;
  if n_erfasst < 6 or n_dabei * 100 < v_schwelle * n_erfasst then return null; end if;
  return case when n_dabei = n_erfasst then 'bei jedem Training dabei' else 'bei fast jedem Training dabei' end;
end $$;
revoke all on function public.portraet_beteiligung(bigint) from public, anon;
grant execute on function public.portraet_beteiligung(bigint) to authenticated;

-- 9) Benachrichtigungen: genau einmal je Konto und Art (Protokoll), Ruhezeit je Konto wie v705.

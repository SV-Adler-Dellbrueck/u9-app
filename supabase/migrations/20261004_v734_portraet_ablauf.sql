create or replace function public.portraet_push_faellig(p_jetzt timestamptz default now())
returns table(user_id uuid, titel text, text text, url text)
language plpgsql security definer set search_path = public as $$
#variable_conflict use_column
declare v_lokal timestamp := p_jetzt at time zone 'Europe/Berlin';
begin
  return query
  with e as (
    select pe.*, k.name kind, (pe.frist_trainer at time zone 'Europe/Berlin')::date fr_tag
      from portraet_einreichung pe join kader k on k.id = pe.spieler_id
     where pe.status <> 'uebernommen' and p_jetzt < pe.frist_trainer
  ), eltern as (
    select distinct e.id eid, e.kind, e.status, e.frist_eltern, u.id uid
      from e join eltern_kinder ek on ek.spieler_id = e.spieler_id
      join auth.users u on lower(u.email) = lower(ek.email)
  ), trainer as (
    select e.id eid, e.kind, e.fr_tag, p.id uid,
           exists (select 1 from portraet_trainerstimme s where s.einreichung_id = e.id and s.trainer_id = p.id) hat_stimme
      from e cross join profiles p where p.role = 'trainer'
  ), kand as (
    select el.eid, el.uid, 'eltern_anfrage'::text art, el.kind from eltern el
     where el.status = 'angefragt'
    union all
    select el.eid, el.uid, 'eltern_erinnerung', el.kind from eltern el
     where el.status = 'angefragt' and p_jetzt >= el.frist_eltern
       and exists (select 1 from portraet_push_log l where l.einreichung_id = el.eid and l.user_id = el.uid
                    and l.art = 'eltern_anfrage' and l.gesendet_am < el.frist_eltern)
    union all
    select tr.eid, tr.uid, 'trainer_hinweis', tr.kind from trainer tr
     where v_lokal >= (tr.fr_tag - 4) + time '09:00'                -- ab Montag 9 Uhr der Spieltagswoche
    union all
    select tr.eid, tr.uid, 'trainer_erinnerung', tr.kind from trainer tr
     where not tr.hat_stimme and v_lokal >= tr.fr_tag + time '08:00'  -- Freitagmorgen
  ), bereit as (
    select k.* from kand k
     where exists (select 1 from push_subscriptions ps where ps.user_id = k.uid)
       and not public.push_ruht(k.uid, p_jetzt)
  ), gemerkt as (
    insert into portraet_push_log(einreichung_id, user_id, art)
    select b.eid, b.uid, b.art from bereit b
    on conflict do nothing
    returning portraet_push_log.einreichung_id, portraet_push_log.user_id, portraet_push_log.art
  )
  select b.uid,
         case b.art when 'eltern_anfrage' then '🪺 ' || split_part(b.kind,' ',1) || ' ist im nächsten Adler Nest'
                    when 'eltern_erinnerung' then '🪺 Noch Zeit fürs Porträt'
                    when 'trainer_hinweis' then '🪺 Porträt: ' || split_part(b.kind,' ',1)
                    else '🪺 Deine Stimme fürs Porträt fehlt' end,
         case b.art when 'eltern_anfrage' then 'Füllt bis Mittwoch 20 Uhr den kurzen Porträt-Bogen aus – Fan-Fakten und auf Wunsch bis zu zwei Fotos.'
                    when 'eltern_erinnerung' then 'Der Porträt-Bogen ist noch offen. Ein paar Angaben reichen schon.'
                    when 'trainer_hinweis' then 'Bis Freitag 20 Uhr: zwei, drei Stichpunkte – was das Kind auszeichnet, woran es arbeitet.'
                    else 'Bis heute 20 Uhr: zwei, drei Stichpunkte zum Porträtkind.' end,
         case when b.art like 'eltern%' then './eltern/?portal&nest=bogen' else './trainer/?nest=ablauf' end
    from bereit b
    join gemerkt g on g.einreichung_id = b.eid and g.user_id = b.uid and g.art = b.art;
end $$;
revoke all on function public.portraet_push_faellig(timestamptz) from public, anon, authenticated;
grant execute on function public.portraet_push_faellig(timestamptz) to service_role;

-- 10) Trainerstimmen reichen in die Hüllfunktion der Leseansicht NICHT hinein (heft_ausgabe_lesen bleibt unverändert).

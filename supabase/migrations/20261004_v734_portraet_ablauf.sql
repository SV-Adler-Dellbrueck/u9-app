-- v734 (Auftragspaket Adler Nest, Abschnitt 8 „Porträt-Ablauf“, beschlossen 03.10.2026):
-- Porträt-Angaben werden über einen festen Ablauf eingeholt – Eltern bis Mittwoch 20 Uhr, Trainer bis Freitag
-- 20 Uhr vor dem Spieltag. Trainingsbeteiligung erscheint nur ab einer Schwelle (Standard 90 %) und nur aus der
-- tatsächlichen Anwesenheit (Tabelle anwesenheit), nie aus Zusagen.
-- Benachrichtigungen: portraet_push_faellig() entscheidet wie wiewars_push_faellig() in der Datenbank und merkt
-- sich jeden Versand; verschickt wird im vorhandenen 5-Minuten-Lauf rufe-push. Kein neuer Cron-Job.

-- 1) Einreichung je Porträt
create table if not exists public.portraet_einreichung (
  id bigint generated by default as identity primary key,
  spieler_id bigint not null references public.kader(id) on delete cascade,
  termin_id bigint references public.termine(id) on delete set null,   -- Spieltag, nach dem die Ausgabe erscheint
  ausgabe_id bigint references public.heft_ausgabe(id) on delete set null,
  status text not null default 'angefragt' check (status in ('angefragt','eingereicht','uebernommen')),
  einverstanden_am timestamptz,
  einverstanden_von uuid,
  privatfotos jsonb not null default '[]'::jsonb
    check (jsonb_typeof(privatfotos) = 'array' and jsonb_array_length(privatfotos) <= 2),
  frist_eltern timestamptz not null,
  frist_trainer timestamptz not null,
  erinnert_am timestamptz,
  angelegt_von uuid default auth.uid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
comment on table public.portraet_einreichung is 'v734: Porträt-Angaben je Kind und Ausgabe – Eltern lesen nur die Zeile ihres Kindes, solange nicht übernommen';
create unique index if not exists portraet_einreichung_offen_kind on public.portraet_einreichung(spieler_id) where status <> 'uebernommen';
create unique index if not exists portraet_einreichung_offen_termin on public.portraet_einreichung(termin_id) where status <> 'uebernommen' and termin_id is not null;

